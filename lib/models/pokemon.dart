class Pokemon {
  final int id;
  final String name;
  final string image;
  final String type;
  final double height; // cm
  final double weight; // kg
  final List<String> ability;
  

  const Pokemon({
    required this.id,
    required this.name,
    required this.image,
    required this.type,
    required this.height,
    required this.weight,
    required this.ability,
  });
}
